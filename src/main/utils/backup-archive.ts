import { createReadStream, createWriteStream, type ReadStream } from 'fs'
import { lstat, mkdir, open, readdir, rename, rm, utimes } from 'fs/promises'
import { dirname, join, resolve, sep } from 'path'
import { pipeline } from 'stream/promises'
import yazl from 'yazl'
import yauzl from 'yauzl'
import { isUnsafeModpackPath } from '../../shared/utils/modpack'

/**
 * The archive side of server backups: what a backup covers, writing one,
 * reading one back and swapping it into a server directory.
 *
 * Nothing here knows about Electron, the database or running servers, so it
 * can be tested against plain directories.
 *
 * A backup is a standard zip (zip64 when it has to be), written and read as a
 * stream: worlds run to many gigabytes and must never be held in memory.
 */

/**
 * Top-level entries of a server directory that a backup leaves out, and that
 * a restore therefore leaves alone. They are either regenerated by the server
 * software (libraries, versions, cache) or are a record of the past that a
 * restore should not rewrite (logs, crash reports).
 */
export const BACKUP_EXCLUDED_TOP_LEVEL: readonly string[] = [
  'logs',
  'crash-reports',
  'debug',
  'cache',
  'libraries',
  'versions',
  'modpack.mrpack'
]

/**
 * Whether a top-level entry of a server directory belongs to backups. This is
 * the single rule for both directions: a backup contains exactly the covered
 * entries, and a restore replaces exactly the covered entries.
 */
export function isBackedUpTopLevel(name: string): boolean {
  if (!name || name === '.' || name === '..') return false
  return !BACKUP_EXCLUDED_TOP_LEVEL.includes(name.toLowerCase())
}

/**
 * Files skipped wherever they are. `session.lock` is held open by the running
 * server (unreadable on Windows) and is recreated on start.
 */
function isSkippedFile(name: string): boolean {
  return name === 'session.lock'
}

/** Already-compressed formats are stored as they are: compressing again only costs time. */
const STORED_EXTENSIONS = new Set([
  'mca', 'mcc', 'mcr', 'dat', 'dat_old', 'nbt', 'jar', 'zip', 'gz', 'png', 'jpg', 'jpeg', 'ogg', 'mrpack'
])

function shouldCompress(relPath: string): boolean {
  const dot = relPath.lastIndexOf('.')
  if (dot < 0) return true
  return !STORED_EXTENSIONS.has(relPath.slice(dot + 1).toLowerCase())
}

export class BackupAbortedError extends Error {
  constructor(reason?: string) {
    super(reason ? `Cancelled: ${reason}` : 'Cancelled')
    this.name = 'BackupAbortedError'
  }
}

function abortError(signal?: AbortSignal): BackupAbortedError {
  const reason = signal?.reason
  return new BackupAbortedError(typeof reason === 'string' ? reason : undefined)
}

function throwIfAborted(signal?: AbortSignal): void {
  if (signal?.aborted) throw abortError(signal)
}

interface PlannedFile {
  abs: string
  /** Path inside the archive, with forward slashes. */
  rel: string
  size: number
  mtime: Date
}

export interface BackupPlan {
  files: PlannedFile[]
  /** Directories with nothing in them, kept so the layout survives. */
  emptyDirs: string[]
  totalBytes: number
  /** Entries left out because they cannot be backed up (links, unreadable files). */
  skipped: string[]
}

/** Walk a server directory and list what a backup of it contains. */
export async function planBackup(serverDir: string, signal?: AbortSignal): Promise<BackupPlan> {
  const plan: BackupPlan = { files: [], emptyDirs: [], totalBytes: 0, skipped: [] }

  const walk = async (absDir: string, relDir: string): Promise<void> => {
    throwIfAborted(signal)
    const entries = await readdir(absDir, { withFileTypes: true })
    let kept = 0
    for (const entry of entries) {
      const rel = relDir ? `${relDir}/${entry.name}` : entry.name
      if (!relDir && !isBackedUpTopLevel(entry.name)) continue
      const abs = join(absDir, entry.name)

      // Links and junctions could lead out of the server directory.
      if (entry.isSymbolicLink()) {
        plan.skipped.push(rel)
        continue
      }
      if (entry.isDirectory()) {
        kept++
        await walk(abs, rel)
        continue
      }
      if (!entry.isFile() || isSkippedFile(entry.name)) continue

      let info
      try {
        info = await lstat(abs)
        // Find out now whether it can be read at all, rather than fail halfway.
        const handle = await open(abs, 'r')
        await handle.close()
      } catch {
        plan.skipped.push(rel)
        continue
      }
      kept++
      plan.files.push({ abs, rel, size: info.size, mtime: info.mtime })
      plan.totalBytes += info.size
    }
    if (kept === 0 && relDir) plan.emptyDirs.push(relDir)
  }

  await walk(serverDir, '')
  return plan
}

export interface ArchiveProgress {
  doneBytes: number
  totalBytes: number
}

export interface WriteArchiveOptions {
  signal?: AbortSignal
  onProgress?: (progress: ArchiveProgress) => void
  /** Stored in the zip comment; read back with `readArchiveComment`. */
  comment?: string
}

/**
 * Write a plan to `destPath`. The archive is written next to it as `.part`
 * and renamed when complete, so a file with the final name is always whole.
 */
export async function writeArchive(plan: BackupPlan, destPath: string, options: WriteArchiveOptions = {}): Promise<void> {
  const { signal, onProgress, comment } = options
  throwIfAborted(signal)
  await mkdir(dirname(destPath), { recursive: true })
  const partPath = `${destPath}.part`

  const zip = new yazl.ZipFile()
  const output = createWriteStream(partPath)
  let doneBytes = 0

  try {
    await new Promise<void>((resolvePromise, reject) => {
      let settled = false
      // The file being read right now. It is closed on failure: an open
      // handle would keep the world folder from being renamed (Windows).
      let reading: ReadStream | undefined
      const fail = (err: unknown): void => {
        if (settled) return
        settled = true
        reading?.destroy()
        output.destroy()
        reject(err)
      }
      const onAbort = (): void => fail(abortError(signal))
      signal?.addEventListener('abort', onAbort, { once: true })

      zip.on('error', fail)
      pipeline(zip.outputStream, output).then(
        () => {
          signal?.removeEventListener('abort', onAbort)
          if (!settled) {
            settled = true
            resolvePromise()
          }
        },
        (err) => fail(signal?.aborted ? abortError(signal) : err)
      )

      for (const file of plan.files) {
        // Lazily: one file is open at a time, however many there are. The size
        // is not promised up front, so a file a plugin appends to in the
        // meantime does not break the archive.
        zip.addReadStreamLazy(file.rel, { mtime: file.mtime, compress: shouldCompress(file.rel) }, (cb) => {
          if (signal?.aborted) {
            cb(abortError(signal), null as never)
            return
          }
          const stream = createReadStream(file.abs)
          reading = stream
          stream.on('data', (chunk) => {
            doneBytes += chunk.length
            onProgress?.({ doneBytes, totalBytes: plan.totalBytes })
          })
          // A file that went away or became unreadable since the plan was
          // made fails the backup; it must not be left hanging or incomplete.
          stream.on('error', (err) => fail(new Error(`Could not read ${file.rel}: ${err.message}`)))
          cb(null, stream)
        })
      }
      try {
        for (const dir of plan.emptyDirs) zip.addEmptyDirectory(dir)
        zip.end({ forceZip64Format: false, comment: comment ?? '' })
      } catch (err) {
        fail(err)
      }
    })
    await rename(partPath, destPath)
  } catch (err) {
    await rm(partPath, { force: true }).catch(() => undefined)
    throw err
  }
}

function openZip(zipPath: string): Promise<yauzl.ZipFile> {
  return new Promise((resolvePromise, reject) => {
    yauzl.open(zipPath, { lazyEntries: true, autoClose: false, strictFileNames: true }, (err, zipfile) => {
      if (err || !zipfile) reject(err ?? new Error('Could not open the archive'))
      else resolvePromise(zipfile)
    })
  })
}

/** The comment of an archive (the backup manifest), or '' when it has none. */
export async function readArchiveComment(zipPath: string): Promise<string> {
  const zipfile = await openZip(zipPath)
  try {
    return zipfile.comment ?? ''
  } finally {
    zipfile.close()
  }
}

function isInside(root: string, target: string): boolean {
  const base = resolve(root)
  const full = resolve(target)
  return full.startsWith(base + sep)
}

/** Unix file type bits of a zip entry, when the archive records them. */
function isSymlinkEntry(entry: yauzl.Entry): boolean {
  return ((entry.externalFileAttributes >>> 16) & 0o170000) === 0o120000
}

export interface ExtractOptions {
  signal?: AbortSignal
  onProgress?: (progress: ArchiveProgress) => void
}

/**
 * Extract a backup into `destDir` (created empty by the caller).
 *
 * The archive is not trusted, even though the app wrote it: it sat on disk
 * where anything could have replaced it. Any entry that is a link, has a path
 * leading out of `destDir`, or lies outside what backups cover makes the whole
 * extraction fail; nothing is skipped silently.
 */
export async function extractArchive(zipPath: string, destDir: string, options: ExtractOptions = {}): Promise<number> {
  const { signal, onProgress } = options
  throwIfAborted(signal)
  const zipfile = await openZip(zipPath)
  let fileCount = 0
  let doneBytes = 0
  let totalBytes = 0

  try {
    // First pass over the directory of the archive: validate everything before
    // a single byte is written.
    const entries: yauzl.Entry[] = []
    await new Promise<void>((resolvePromise, reject) => {
      zipfile.on('error', reject)
      zipfile.on('end', resolvePromise)
      zipfile.on('entry', (entry: yauzl.Entry) => {
        entries.push(entry)
        zipfile.readEntry()
      })
      zipfile.readEntry()
    })

    for (const entry of entries) {
      const name = entry.fileName
      const clean = name.endsWith('/') ? name.slice(0, -1) : name
      if (isUnsafeModpackPath(clean) || !isInside(destDir, join(destDir, clean))) {
        throw new Error(`The backup contains an unsafe path: ${name}`)
      }
      if (isSymlinkEntry(entry)) {
        throw new Error(`The backup contains a link, which is not allowed: ${name}`)
      }
      // Windows drops a trailing dot or space and reads "a:b" as a stream of
      // "a", so such a name could stand for a path the checks did not see.
      if (clean.split('/').some((segment) => /[. ]$/.test(segment) || segment.includes(':'))) {
        throw new Error(`The backup contains a file name that is not allowed: ${name}`)
      }
      if (!isBackedUpTopLevel(clean.split('/')[0])) {
        throw new Error(`The backup contains a path that backups do not cover: ${name}`)
      }
      if (!name.endsWith('/')) totalBytes += entry.uncompressedSize
    }

    for (const entry of entries) {
      throwIfAborted(signal)
      const target = join(destDir, entry.fileName)
      if (entry.fileName.endsWith('/')) {
        await mkdir(target, { recursive: true })
        continue
      }
      await mkdir(dirname(target), { recursive: true })
      const source = await new Promise<NodeJS.ReadableStream>((resolvePromise, reject) => {
        zipfile.openReadStream(entry, (err, stream) => {
          if (err || !stream) reject(err ?? new Error(`Could not read ${entry.fileName}`))
          else resolvePromise(stream)
        })
      })
      source.on('data', (chunk: Buffer) => {
        doneBytes += chunk.length
        onProgress?.({ doneBytes, totalBytes })
      })
      // 'wx': the staging directory starts empty, so an existing file means
      // the archive names the same path twice.
      await pipeline(source, createWriteStream(target, { flags: 'wx' }), { signal })
      const mtime = entry.getLastModDate()
      await utimes(target, mtime, mtime).catch(() => undefined)
      fileCount++
    }
    return fileCount
  } catch (err) {
    if (signal?.aborted) throw abortError(signal)
    throw err
  } finally {
    zipfile.close()
  }
}

/**
 * Replace the backed-up part of `serverDir` with the contents of `stageDir`.
 *
 * Covered entries of the server directory are moved aside into `asideDir`,
 * then the staged ones are moved in. These are renames within one volume, so
 * nothing is copied and nothing is deleted until everything is in place. If
 * any move fails (on Windows: a file is still open somewhere), every move is
 * undone and the server directory is as it was.
 *
 * Covered files that are not in the backup do not survive: a world must not
 * end up as a mix of two points in time. Entries backups do not cover stay.
 */
export async function swapIntoServerDir(serverDir: string, stageDir: string, asideDir: string): Promise<void> {
  await mkdir(asideDir, { recursive: false })
  const movedAside: string[] = []
  const movedIn: string[] = []

  try {
    for (const name of await readdir(serverDir)) {
      if (!isBackedUpTopLevel(name)) continue
      await rename(join(serverDir, name), join(asideDir, name))
      movedAside.push(name)
    }
    for (const name of await readdir(stageDir)) {
      await rename(join(stageDir, name), join(serverDir, name))
      movedIn.push(name)
    }
  } catch (err) {
    const undo: string[] = []
    for (const name of movedIn.reverse()) {
      await rename(join(serverDir, name), join(stageDir, name)).catch((e) => undo.push(String(e)))
    }
    for (const name of movedAside.reverse()) {
      await rename(join(asideDir, name), join(serverDir, name)).catch((e) => undo.push(String(e)))
    }
    if (undo.length === 0) await rm(asideDir, { recursive: true, force: true }).catch(() => undefined)
    const message = err instanceof Error ? err.message : String(err)
    throw new Error(
      undo.length === 0
        ? `Could not replace the server files (is one of them open in another program?): ${message}`
        : `Could not replace the server files, and could not put all of them back. The previous files are in ${asideDir}. ${message}`
    )
  }

  // Everything is in place; the previous files can go.
  try {
    await rm(asideDir, { recursive: true, force: true, maxRetries: 5, retryDelay: 200 })
  } catch {
    throw new Error(
      `The backup was restored, but the previous files could not be removed. Delete the folder ${asideDir} by hand before starting the server.`
    )
  }
}
