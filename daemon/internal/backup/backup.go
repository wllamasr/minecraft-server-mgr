// Package backup reads and writes backups of a server directory.
//
// A backup is a zip archive of the directory minus what the server software
// regenerates, with a manifest (JSON) in the zip comment. The format and the
// rules are the ones the desktop app uses for local servers
// (src/main/utils/backup-archive.ts): the same entries are left out, the same
// archives are refused on restore, and a restore swaps the same entries.
//
// Nothing here knows about running servers; the server package drives it.
package backup

import (
	"archive/zip"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"
	"unicode/utf16"
)

// excludedTopLevel are the top-level entries of a server directory that a
// backup leaves out, and that a restore therefore leaves alone. They are
// either regenerated by the server software or a record of the past that a
// restore should not rewrite.
var excludedTopLevel = map[string]bool{
	"logs":           true,
	"crash-reports":  true,
	"debug":          true,
	"cache":          true,
	"libraries":      true,
	"versions":       true,
	"modpack.mrpack": true,
}

// Covered reports whether a top-level entry of a server directory belongs to
// backups. It is the single rule for both directions: a backup contains
// exactly the covered entries, and a restore replaces exactly those.
func Covered(name string) bool {
	if name == "" || name == "." || name == ".." {
		return false
	}
	return !excludedTopLevel[strings.ToLower(name)]
}

// skippedFile is left out wherever it is: the running server holds it open
// and recreates it on start.
func skippedFile(name string) bool { return name == "session.lock" }

// storedExtensions are already compressed: compressing again only costs time.
var storedExtensions = map[string]bool{
	"mca": true, "mcc": true, "mcr": true, "dat": true, "dat_old": true, "nbt": true, "jar": true,
	"zip": true, "gz": true, "png": true, "jpg": true, "jpeg": true, "ogg": true, "mrpack": true,
}

func method(rel string) uint16 {
	if dot := strings.LastIndexByte(rel, '.'); dot >= 0 && storedExtensions[strings.ToLower(rel[dot+1:])] {
		return zip.Store
	}
	return zip.Deflate
}

// ErrCancelled is what an operation that was told to stop returns (wrapped,
// with the reason).
var ErrCancelled = errors.New("Cancelled")

// Cancelled returns the cancellation error of ctx, or nil while it is live.
func Cancelled(ctx context.Context) error {
	if ctx.Err() == nil {
		return nil
	}
	cause := context.Cause(ctx)
	if cause == nil || errors.Is(cause, context.Canceled) {
		return ErrCancelled
	}
	return fmt.Errorf("%w: %s", ErrCancelled, cause.Error())
}

// File is one file of a plan.
type File struct {
	Abs     string
	Rel     string // slash-separated, relative to the server directory
	Size    int64
	ModTime time.Time
}

// Plan is what a backup will contain.
type Plan struct {
	Files []File
	// EmptyDirs are directories with nothing in them, kept so the layout survives.
	EmptyDirs  []string
	TotalBytes int64
	// Skipped are entries left out because they cannot be backed up (links,
	// special files, unreadable files).
	Skipped []string
}

// MakePlan lists what a backup of dir contains.
func MakePlan(ctx context.Context, dir string) (*Plan, error) {
	plan := &Plan{}
	var walk func(abs, rel string) error
	walk = func(abs, rel string) error {
		if err := Cancelled(ctx); err != nil {
			return err
		}
		entries, err := os.ReadDir(abs)
		if err != nil {
			if rel == "" {
				return err
			}
			plan.Skipped = append(plan.Skipped, rel)
			return nil
		}
		kept := 0
		for _, entry := range entries {
			name := entry.Name()
			if rel == "" && !Covered(name) {
				continue
			}
			childRel := name
			if rel != "" {
				childRel = rel + "/" + name
			}
			childAbs := filepath.Join(abs, name)
			mode := entry.Type()
			switch {
			case mode&(os.ModeSymlink|os.ModeIrregular) != 0:
				// A link (or a Windows junction) could lead anywhere; it is never followed.
				plan.Skipped = append(plan.Skipped, childRel)
			case mode.IsDir():
				kept++
				if err := walk(childAbs, childRel); err != nil {
					return err
				}
			case mode.IsRegular():
				if skippedFile(name) {
					continue
				}
				info, err := entry.Info()
				if err != nil {
					plan.Skipped = append(plan.Skipped, childRel)
					continue
				}
				kept++
				plan.Files = append(plan.Files, File{Abs: childAbs, Rel: childRel, Size: info.Size(), ModTime: info.ModTime()})
				plan.TotalBytes += info.Size()
			default:
				plan.Skipped = append(plan.Skipped, childRel)
			}
		}
		if kept == 0 && rel != "" {
			plan.EmptyDirs = append(plan.EmptyDirs, rel)
		}
		return nil
	}
	if err := walk(dir, ""); err != nil {
		return nil, err
	}
	return plan, nil
}

// Progress reports how far a copy has got.
type Progress func(doneBytes, totalBytes int64)

// ctxReader fails once ctx is cancelled and counts what went through.
type ctxReader struct {
	ctx      context.Context
	r        io.Reader
	done     *int64
	total    int64
	progress Progress
}

func (c *ctxReader) Read(p []byte) (int, error) {
	if err := Cancelled(c.ctx); err != nil {
		return 0, err
	}
	n, err := c.r.Read(p)
	if n > 0 {
		*c.done += int64(n)
		if c.progress != nil {
			c.progress(*c.done, c.total)
		}
	}
	return n, err
}

// Write writes plan to dest. The archive is written next to it as ".part" and
// renamed when complete and flushed, so a file with the final name is always
// whole. comment is stored in the zip comment (see ReadComment).
func Write(ctx context.Context, plan *Plan, dest, comment string, progress Progress) (err error) {
	if err := Cancelled(ctx); err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(dest), 0o750); err != nil {
		return err
	}
	part := dest + ".part"
	out, err := os.OpenFile(part, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o640)
	if err != nil {
		return err
	}
	closed := false
	defer func() {
		if !closed {
			_ = out.Close()
		}
		if err != nil {
			_ = os.Remove(part)
		}
	}()

	zw := zip.NewWriter(out)
	if err := zw.SetComment(comment); err != nil {
		return err
	}
	var done int64
	for _, file := range plan.Files {
		if err := Cancelled(ctx); err != nil {
			return err
		}
		header := &zip.FileHeader{Name: file.Rel, Method: method(file.Rel), Modified: file.ModTime}
		header.SetMode(0o644)
		w, err := zw.CreateHeader(header)
		if err != nil {
			return err
		}
		if err := copyFile(ctx, w, file, &done, plan.TotalBytes, progress); err != nil {
			return err
		}
	}
	for _, dir := range plan.EmptyDirs {
		header := &zip.FileHeader{Name: dir + "/", Method: zip.Store}
		header.SetMode(os.ModeDir | 0o755)
		if _, err := zw.CreateHeader(header); err != nil {
			return err
		}
	}
	if err := zw.Close(); err != nil {
		return err
	}
	// On disk before it gets its final name.
	if err := out.Sync(); err != nil {
		return err
	}
	closed = true
	if err := out.Close(); err != nil {
		return err
	}
	if err := Cancelled(ctx); err != nil {
		return err
	}
	return os.Rename(part, dest)
}

func copyFile(ctx context.Context, w io.Writer, file File, done *int64, total int64, progress Progress) error {
	src, err := os.Open(file.Abs)
	if err != nil {
		// A file that went away or became unreadable since the plan was made
		// fails the backup; it must not be silently incomplete.
		return fmt.Errorf("could not read %s: %w", file.Rel, err)
	}
	defer src.Close()
	// Never more than the size the plan (and so the manifest) counted: a file
	// the running server appends to meanwhile must not make the archive hold
	// more than it says, which a restore would refuse.
	limited := io.LimitReader(src, file.Size)
	if _, err := io.Copy(w, &ctxReader{ctx: ctx, r: limited, done: done, total: total, progress: progress}); err != nil {
		if errors.Is(err, ErrCancelled) {
			return err
		}
		return fmt.Errorf("could not read %s: %w", file.Rel, err)
	}
	return nil
}

// ReadComment returns the zip comment of an archive.
func ReadComment(zipPath string) (string, error) {
	r, err := zip.OpenReader(zipPath)
	if err != nil {
		return "", err
	}
	defer r.Close()
	return r.Comment, nil
}

var deviceName = regexp.MustCompile(`(?i)^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)`)

// checkEntryName returns the clean, slash-separated path of an archive entry,
// or an error when the name must not be unpacked.
func checkEntryName(name string) (string, error) {
	bad := func(why string) (string, error) {
		return "", fmt.Errorf("the backup contains a path that is not allowed (%s): %q", why, name)
	}
	if name == "" || strings.ContainsRune(name, '\\') || strings.HasPrefix(name, "/") {
		return bad("not a relative path")
	}
	clean := strings.TrimSuffix(name, "/")
	if clean == "" || path.Clean(clean) != clean {
		return bad("not a plain path")
	}
	for _, segment := range strings.Split(clean, "/") {
		switch {
		case segment == "" || segment == "." || segment == "..":
			return bad("not a plain path")
		case strings.ContainsRune(segment, ':'):
			// Windows reads "a:b" as a stream of "a", or as a drive.
			return bad("colon")
		case strings.HasSuffix(segment, ".") || strings.HasSuffix(segment, " "):
			// Windows drops a trailing dot or space: the name would stand for another path.
			return bad("trailing dot or space")
		case deviceName.MatchString(segment):
			return bad("device name")
		}
		for _, r := range segment {
			if r < 0x20 {
				return bad("control character")
			}
		}
	}
	if !Covered(strings.Split(clean, "/")[0]) {
		return "", fmt.Errorf("the backup contains %q, which backups do not cover", name)
	}
	return clean, nil
}

// Extract unpacks an archive into destDir, which must exist and be empty, and
// returns the number of files written. Every entry is checked before anything
// is written: a link, a path outside destDir, an entry backups do not cover or
// a name the file system would read as something else refuses the archive.
// maxBytes bounds what the archive may unpack to (its manifest says how much).
func Extract(ctx context.Context, zipPath, destDir string, maxBytes int64, progress Progress) (int, error) {
	r, err := zip.OpenReader(zipPath)
	if err != nil {
		return 0, err
	}
	defer r.Close()

	type entry struct {
		file  *zip.File
		clean string
		dir   bool
	}
	entries := make([]entry, 0, len(r.File))
	seen := map[string]bool{}
	var total uint64
	for _, f := range r.File {
		clean, err := checkEntryName(f.Name)
		if err != nil {
			return 0, err
		}
		mode := f.Mode()
		isDir := strings.HasSuffix(f.Name, "/")
		if mode&os.ModeSymlink != 0 {
			return 0, fmt.Errorf("the backup contains a link, which is not allowed: %q", f.Name)
		}
		if !isDir && mode.Type() != 0 {
			return 0, fmt.Errorf("the backup contains a special file, which is not allowed: %q", f.Name)
		}
		// Two names that differ only in case are one file on Windows.
		key := strings.ToLower(clean)
		if seen[key] {
			return 0, fmt.Errorf("the backup contains %q more than once", f.Name)
		}
		seen[key] = true
		if !isDir {
			total += f.UncompressedSize64
			if total > uint64(maxBytes) {
				return 0, errors.New("the backup holds more data than it says")
			}
		}
		entries = append(entries, entry{file: f, clean: clean, dir: isDir})
	}

	var done int64
	count := 0
	for _, e := range entries {
		if err := Cancelled(ctx); err != nil {
			return 0, err
		}
		target := filepath.Join(destDir, filepath.FromSlash(e.clean))
		if e.dir {
			if err := os.MkdirAll(target, 0o750); err != nil {
				return 0, err
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(target), 0o750); err != nil {
			return 0, err
		}
		if err := extractFile(ctx, e.file, target, &done, int64(total), progress); err != nil {
			return 0, err
		}
		count++
	}
	return count, nil
}

func extractFile(ctx context.Context, f *zip.File, target string, done *int64, total int64, progress Progress) error {
	src, err := f.Open()
	if err != nil {
		return err
	}
	defer src.Close()
	// Never the mode from the archive, and never over an existing file.
	out, err := os.OpenFile(target, os.O_CREATE|os.O_EXCL|os.O_WRONLY, 0o640)
	if err != nil {
		return err
	}
	// One byte more than announced is enough to tell that the entry lies.
	limit := int64(f.UncompressedSize64)
	n, err := io.Copy(out, &ctxReader{ctx: ctx, r: io.LimitReader(src, limit+1), done: done, total: total, progress: progress})
	if cerr := out.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return err
	}
	if n != limit {
		return fmt.Errorf("the backup is damaged: %q is not the size it says", f.Name)
	}
	if !f.Modified.IsZero() {
		_ = os.Chtimes(target, f.Modified, f.Modified)
	}
	return nil
}

// LeftoverError says that a restore went through and only the folder with
// the replaced files could not be removed.
type LeftoverError struct{ Dir string }

func (e *LeftoverError) Error() string {
	return fmt.Sprintf("The backup was restored, but the previous files could not be removed. Delete the folder %s by hand before starting the server.", e.Dir)
}

// Swap replaces the covered top-level entries of serverDir with the entries
// of stageDir. The current ones are moved to asideDir first (which must not
// exist) and removed at the end; any failure moves everything back.
//
// Covered files that are not in the backup do not survive: a world must not
// end up as a mix of two points in time. Entries backups do not cover stay.
func Swap(serverDir, stageDir, asideDir string) error {
	if err := os.Mkdir(asideDir, 0o750); err != nil {
		return fmt.Errorf("could not prepare the restore: %w", err)
	}
	current, err := os.ReadDir(serverDir)
	if err != nil {
		_ = os.Remove(asideDir)
		return err
	}
	staged, err := os.ReadDir(stageDir)
	if err != nil {
		_ = os.Remove(asideDir)
		return err
	}

	var movedAside, movedIn []string
	fail := func(cause error) error {
		// Put things back, newest move first.
		var undoErr error
		for i := len(movedIn) - 1; i >= 0; i-- {
			if err := os.Rename(filepath.Join(serverDir, movedIn[i]), filepath.Join(stageDir, movedIn[i])); err != nil && undoErr == nil {
				undoErr = err
			}
		}
		for i := len(movedAside) - 1; i >= 0; i-- {
			if err := os.Rename(filepath.Join(asideDir, movedAside[i]), filepath.Join(serverDir, movedAside[i])); err != nil && undoErr == nil {
				undoErr = err
			}
		}
		if undoErr != nil {
			return fmt.Errorf("Could not replace the server files (%v), and could not put them all back (%v). The files that were being replaced are in %s.", cause, undoErr, asideDir)
		}
		_ = os.Remove(asideDir)
		return fmt.Errorf("Could not replace the server files, they were left as they were: %w", cause)
	}

	for _, entry := range current {
		if !Covered(entry.Name()) {
			continue
		}
		if err := os.Rename(filepath.Join(serverDir, entry.Name()), filepath.Join(asideDir, entry.Name())); err != nil {
			return fail(err)
		}
		movedAside = append(movedAside, entry.Name())
	}
	for _, entry := range staged {
		if err := os.Rename(filepath.Join(stageDir, entry.Name()), filepath.Join(serverDir, entry.Name())); err != nil {
			return fail(err)
		}
		movedIn = append(movedIn, entry.Name())
	}

	// Everything is in place; the previous files can go.
	var rmErr error
	for attempt := 0; attempt < 5; attempt++ {
		if rmErr = os.RemoveAll(asideDir); rmErr == nil {
			return nil
		}
		time.Sleep(200 * time.Millisecond)
	}
	return &LeftoverError{Dir: asideDir}
}

// Manifest is what a backup says about itself, stored in the zip comment.
type Manifest struct {
	Format           int     `json:"format"`
	ServerID         string  `json:"serverId"`
	ServerName       string  `json:"serverName"`
	MinecraftVersion string  `json:"minecraftVersion"`
	ModLoader        *string `json:"modLoader"`
	CreatedAt        string  `json:"createdAt"`
	Kind             string  `json:"kind"`
	WhileRunning     bool    `json:"whileRunning"`
	FileCount        int     `json:"fileCount"`
	TotalBytes       int64   `json:"totalBytes"`
}

// ParseManifest reads a zip comment. ok is false when it is not a manifest.
func ParseManifest(comment string) (m Manifest, ok bool) {
	if strings.TrimSpace(comment) == "" || !strings.HasPrefix(strings.TrimSpace(comment), "{") {
		return Manifest{}, false
	}
	if err := json.Unmarshal([]byte(comment), &m); err != nil {
		return Manifest{}, false
	}
	return m, true
}

// RestorableManifest returns what a restore needs to know from the comment of
// an archive, or an error when the archive is not a usable backup: one
// without a manifest, or with no files, would only empty the server.
func RestorableManifest(comment string) (Manifest, error) {
	var raw struct {
		FileCount  *float64 `json:"fileCount"`
		TotalBytes *float64 `json:"totalBytes"`
	}
	if !strings.HasPrefix(strings.TrimSpace(comment), "{") || json.Unmarshal([]byte(comment), &raw) != nil {
		return Manifest{}, errors.New("This file is damaged or is not a backup made by this software")
	}
	if raw.FileCount == nil || raw.TotalBytes == nil ||
		*raw.FileCount < 1 || *raw.FileCount != float64(int64(*raw.FileCount)) ||
		*raw.TotalBytes < 0 || *raw.TotalBytes != float64(int64(*raw.TotalBytes)) {
		return Manifest{}, errors.New("This backup is damaged: it does not say what it contains")
	}
	m, _ := ParseManifest(comment)
	m.FileCount = int(*raw.FileCount)
	m.TotalBytes = int64(*raw.TotalBytes)
	return m, nil
}

// ASCIIJSON is JSON with every non-ASCII character escaped. A zip comment has
// no declared encoding (readers assume CP437), so a server called "Мой
// сервер" must not be written there as it is.
func ASCIIJSON(v any) (string, error) {
	raw, err := json.Marshal(v)
	if err != nil {
		return "", err
	}
	var b strings.Builder
	for _, r := range string(raw) {
		switch {
		case r >= 0x20 && r < 0x7f:
			b.WriteRune(r)
		case r > 0xffff:
			hi, lo := utf16.EncodeRune(r)
			fmt.Fprintf(&b, `\u%04x\u%04x`, hi, lo)
		default:
			fmt.Fprintf(&b, `\u%04x`, r)
		}
	}
	return b.String(), nil
}

// idPattern is what a backup id looks like: a UTC timestamp and the kind.
var idPattern = regexp.MustCompile(`^(\d{4})(\d{2})(\d{2})-(\d{2})(\d{2})(\d{2})-(manual|pre-restore|scheduled)$`)

// ValidID reports whether id is a backup id this software generates. Ids end
// up in file names, so nothing else is ever accepted.
func ValidID(id string) bool { return idPattern.MatchString(id) }

// NewID makes the id of a backup of the given kind made at now.
func NewID(now time.Time, kind string) string {
	// UTC, so ids sort by time whatever happens to the clock's zone.
	return now.UTC().Format("20060102-150405") + "-" + kind
}

// IDTime returns the time and the kind an id stands for.
func IDTime(id string) (at time.Time, kind string, ok bool) {
	m := idPattern.FindStringSubmatch(id)
	if m == nil {
		return time.Time{}, "", false
	}
	at, err := time.ParseInLocation("20060102-150405", id[:15], time.UTC)
	if err != nil {
		return time.Time{}, "", false
	}
	return at, m[7], true
}

// Info describes one backup on disk.
type Info struct {
	ID        string `json:"id"`
	ServerID  string `json:"serverId"`
	Kind      string `json:"kind"`
	CreatedAt string `json:"createdAt"`
	SizeBytes int64  `json:"sizeBytes"`
	// From the manifest; absent when it cannot be read.
	FileCount        int    `json:"fileCount,omitempty"`
	MinecraftVersion string `json:"minecraftVersion,omitempty"`
	WhileRunning     *bool  `json:"whileRunning,omitempty"`
}

// Describe reads what there is to know about the backup id in dir.
func Describe(dir, serverID, id string) (Info, error) {
	at, kind, ok := IDTime(id)
	if !ok {
		return Info{}, errors.New("invalid backup id")
	}
	zipPath := filepath.Join(dir, id+".zip")
	st, err := os.Stat(zipPath)
	if err != nil {
		return Info{}, err
	}
	info := Info{ID: id, ServerID: serverID, Kind: kind, CreatedAt: at.Format(time.RFC3339), SizeBytes: st.Size()}
	if comment, err := ReadComment(zipPath); err == nil {
		if m, ok := ParseManifest(comment); ok {
			info.FileCount = m.FileCount
			info.MinecraftVersion = m.MinecraftVersion
			running := m.WhileRunning
			info.WhileRunning = &running
		}
	}
	return info, nil
}

// List returns the backups in dir, newest first. A missing dir has none.
func List(dir, serverID string) ([]Info, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		if os.IsNotExist(err) {
			return []Info{}, nil
		}
		return nil, err
	}
	out := []Info{}
	for _, entry := range entries {
		name := entry.Name()
		if entry.IsDir() || !strings.HasSuffix(name, ".zip") {
			continue
		}
		id := strings.TrimSuffix(name, ".zip")
		if !ValidID(id) {
			continue
		}
		if info, err := Describe(dir, serverID, id); err == nil {
			out = append(out, info)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID > out[j].ID })
	return out, nil
}

// SweepPartials removes archives a crash or a kill left half-written.
func SweepPartials(dir string) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return
	}
	for _, entry := range entries {
		if strings.HasSuffix(entry.Name(), ".zip.part") {
			_ = os.Remove(filepath.Join(dir, entry.Name()))
		}
	}
}

var saveLine = regexp.MustCompile(`^(?:\[[^\]]*\]\s*)+:\s(.*?)\s*$`)

// serverMessage returns the message of a line the server itself logged.
//
// A log line is a run of "[...]" groups (time, thread, level), a colon, and
// the message. A chat message or a /say puts something between the colon and
// the text ("<Steve>", "[Server]"), so a player typing "Saved the game" can
// never be taken for the server's confirmation.
func serverMessage(line string) (string, bool) {
	m := saveLine.FindStringSubmatch(line)
	if m == nil {
		return "", false
	}
	return m[1], true
}

// SaveOffAnswer says what the server answered to "save-off": "disabled",
// "already-off", or "" when the line is not that answer.
func SaveOffAnswer(line string) string {
	msg, ok := serverMessage(line)
	if !ok {
		return ""
	}
	switch msg {
	case "Automatic saving is now disabled", "Turned off world auto-saving":
		return "disabled"
	case "Saving is already turned off":
		return "already-off"
	}
	return ""
}

// IsSaveFinished reports whether the line is the server confirming that
// "save-all" has finished.
func IsSaveFinished(line string) bool {
	msg, ok := serverMessage(line)
	return ok && (msg == "Saved the game" || msg == "Saved the world")
}
